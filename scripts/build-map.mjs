// Generates src/data/map.generated.ts from Natural Earth 1:50m country shapes.
// Usage: node scripts/build-map.mjs <path/to/ne_50m_admin_0_countries.geojson>
// Source data: https://github.com/nvkelso/natural-earth-vector (public domain)
// The output is committed, so this only needs to run when the map extent changes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { geoAzimuthalEqualArea, geoPath, geoGraticule } from 'd3-geo';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const src = process.argv[2];
if (!src) {
  console.error('Pass the path to ne_50m_admin_0_countries.geojson');
  process.exit(1);
}

const W = 1000;
const H = 780;
// Extent: Madrid in the south-west, Gothenburg in the north, Budapest/Warsaw in the east.
const extent = {
  type: 'MultiPoint',
  coordinates: [[-9.5, 38.5], [24.5, 38.5], [-9.5, 58.5], [24.5, 58.5], [8, 59.5], [8, 37.2]],
};
const projection = geoAzimuthalEqualArea()
  .rotate([-8.5, -49])
  .fitExtent([[24, 18], [W - 24, H - 18]], extent);
projection.clipExtent([[-2, -2], [W + 2, H + 2]]);

const geo = JSON.parse(fs.readFileSync(src, 'utf8'));
const pathGen = geoPath(projection);

// Douglas-Peucker on projected rings keeps the file small without visible loss.
function simplify(points, tol) {
  if (points.length < 4) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let maxD = 0;
    let idx = -1;
    const [ax, ay] = points[a];
    const [bx, by] = points[b];
    const dx = bx - ax;
    const dy = by - ay;
    const len = Math.hypot(dx, dy) || 1e-9;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = points[i];
      const d = Math.abs(dy * px - dx * py + bx * ay - by * ax) / len;
      if (d > maxD) { maxD = d; idx = i; }
    }
    if (maxD > tol && idx > 0) {
      keep[idx] = 1;
      stack.push([a, idx], [idx, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

function pathToRings(d) {
  const rings = [];
  for (const seg of d.split('M').filter(Boolean)) {
    const closed = seg.includes('Z');
    const pts = seg.replace(/Z/g, '').split('L').map((p) => p.split(',').map(Number));
    rings.push({ pts, closed });
  }
  return rings;
}

function ringsToPath(rings, tol, minArea) {
  let out = '';
  for (const { pts, closed } of rings) {
    const s = simplify(pts, tol);
    if (s.length < 3) continue;
    let area = 0;
    for (let i = 0; i < s.length; i++) {
      const [x1, y1] = s[i];
      const [x2, y2] = s[(i + 1) % s.length];
      area += x1 * y2 - x2 * y1;
    }
    if (Math.abs(area / 2) < minArea) continue;
    out += 'M' + s.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join('L') + (closed ? 'Z' : '');
  }
  return out;
}

let land = '';
for (const f of geo.features) {
  const d = pathGen(f);
  if (!d) continue;
  land += ringsToPath(pathToRings(d), 0.55, 2.5);
}

const gratD = pathGen(geoGraticule().step([5, 5])()) || '';
const graticule = ringsToPath(pathToRings(gratD), 0.4, 0);

const cities = JSON.parse(fs.readFileSync(path.join(root, 'src/data/cities.json'), 'utf8'));
const xy = {};
for (const c of cities) {
  const [x, y] = projection([c.lon, c.lat]);
  xy[c.id] = [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
}

const ts = `// Generated by scripts/build-map.mjs. Do not edit by hand.
// Projection: azimuthal equal-area, rotate [-8.5, -49], viewBox ${W}x${H}.
// Country shapes: Natural Earth 1:50m (public domain).
export const MAP_W = ${W};
export const MAP_H = ${H};
export const LAND_PATH = ${JSON.stringify(land)};
export const GRATICULE_PATH = ${JSON.stringify(graticule)};
export const CITY_XY: Record<string, [number, number]> = ${JSON.stringify(xy)};
`;
fs.writeFileSync(path.join(root, 'src/data/map.generated.ts'), ts);
console.log(`map.generated.ts written: land ${Math.round(land.length / 1024)} KB, graticule ${Math.round(graticule.length / 1024)} KB, ${cities.length} cities`);
